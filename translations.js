// Currently active language code — read by script.js when building the AI prompt
let currentLanguage = "en";

function setLanguage(langCode) {

    if (!TRANSLATIONS[langCode]) {
        langCode = "en";
    }

    currentLanguage = langCode;
    const dict = TRANSLATIONS[langCode];

    // Update every element with a data-i18n attribute (text content)
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    // Update every element with a data-i18n-placeholder attribute
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) {
            el.setAttribute("placeholder", dict[key]);
        }
    });

    // Keep the theme button label correct for the current theme + language
    const themeBtn = document.getElementById("themeBtn");
    if (themeBtn) {
        const isDark = document.body.classList.contains("dark-mode");
        const label = isDark ? dict.theme_light : dict.theme_dark;
        themeBtn.innerHTML = (isDark ? "☀️ " : "🌙 ") + label;
    }

    // Remember choice for next visit
    try {
        localStorage.setItem("mediguide_lang", langCode);
    } catch (e) {
        // ignore if storage is unavailable
    }

    const langSelect = document.getElementById("languageSelect");
    if (langSelect) {
        langSelect.value = langCode;
    }

}

// Apply saved language (if any) as soon as the page loads
document.addEventListener("DOMContentLoaded", function () {
    let saved = "en";
    try {
        saved = localStorage.getItem("mediguide_lang") || "en";
    } catch (e) {
        saved = "en";
    }
    setLanguage(saved);
});